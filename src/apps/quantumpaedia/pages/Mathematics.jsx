import React from 'react';
import { useSearchParams } from 'react-router-dom';
import {
  Sigma,
  Grid3x3,
  Orbit,
  Move3d,
  Boxes,
  FunctionSquare,
  Percent,
  Braces,
  LineChart,
  BookOpen,
} from 'lucide-react';
import { PageHeader, Panel, Chip } from '@/components/common/Kit';
import Formula from '@/components/math/Formula';
import EquationLibrary from '@/components/math/EquationLibrary';
import MatrixCalculator from '@/components/math/MatrixCalculator';
import ComplexVisualiser from '@/components/math/ComplexVisualiser';
import VectorVisualiser from '@/components/math/VectorVisualiser';
import ProbabilityCalculator from '@/components/math/ProbabilityCalculator';
import GraphPlotter from '@/components/math/GraphPlotter';
import DiracExplorer from '@/components/math/DiracExplorer';
import Derivations from '@/components/math/Derivations';

const TABS = [
  { key: 'equations', label: 'Equation Library', icon: Sigma },
  { key: 'linear-algebra', label: 'Linear Algebra', icon: Grid3x3 },
  { key: 'complex', label: 'Complex Numbers', icon: Orbit },
  { key: 'vectors', label: 'Vector Spaces', icon: Move3d },
  { key: 'hilbert', label: 'Hilbert Spaces', icon: Boxes },
  { key: 'operators', label: 'Operators', icon: FunctionSquare },
  { key: 'probability', label: 'Probability', icon: Percent },
  { key: 'dirac', label: 'Dirac Notation', icon: Braces },
  { key: 'graphing', label: 'Graphing', icon: LineChart },
  { key: 'derivations', label: 'Derivations', icon: BookOpen }
];

const CONCEPTS = {
  hilbert: {
    title: 'Hilbert spaces',
    intro:
      'A Hilbert space is a complete complex vector space with an inner product. Completeness guarantees that limiting sequences of states converge, which is what makes spectral decompositions and infinite sums of basis states well defined.',
    points: [
      { tex: '\\langle\\phi|\\psi\\rangle \\in \\mathbb{C},\\quad \\langle\\psi|\\phi\\rangle = \\overline{\\langle\\phi|\\psi\\rangle}', text: 'The inner product is conjugate-symmetric and gives the norm ‖ψ‖ = √⟨ψ|ψ⟩.' },
      { tex: '|\\psi\\rangle = \\sum_n c_n|n\\rangle,\\quad c_n=\\langle n|\\psi\\rangle', text: 'A complete orthonormal basis lets any state be expanded in coefficients.' },
      { tex: '(\\Delta A)^2 = \\langle\\hat A^2\\rangle-\\langle\\hat A\\rangle^2', text: 'Variance of an observable computed from expectation values.' },
      { tex: '\\mathcal{H} = \\mathcal{H}_A\\otimes\\mathcal{H}_B', text: 'Composite systems use tensor products — the formal origin of entanglement.' }
    ],
    note: 'Infinite-dimensional spaces bring unbounded operators and domain subtleties. Position and momentum are not bounded operators, and their eigenstates lie outside the Hilbert space itself — handled rigorously with rigged Hilbert spaces or spectral measures.'
  },
  operators: {
    title: 'Operators and observables',
    intro:
      'Observables are represented by self-adjoint operators. Their real eigenvalues are the possible outcomes; their eigenvectors form a complete orthogonal basis, so any state can be decomposed into a probability distribution over outcomes.',
    points: [
      { tex: '\\hat A|a_n\\rangle = a_n|a_n\\rangle', text: 'Eigenvalue equation: an eigenstate yields a certain outcome.' },
      { tex: '\\hat A^{\\dagger}=\\hat A', text: 'Self-adjointness guarantees real eigenvalues and orthogonal eigenstates.' },
      { tex: '\\hat U^{\\dagger}\\hat U = \\mathbb{1}', text: 'Unitary operators preserve inner products and implement reversible evolution.' },
      { tex: 'e^{-i\\hat H t/\\hbar}', text: 'The time-evolution operator generated by the Hamiltonian.' }
    ],
    note: 'Non-commuting observables cannot be simultaneously diagonalised, so they cannot both have definite values — the algebraic root of complementarity.'
  }
};

export default function Mathematics() {
  const [params, setParams] = useSearchParams();
  const tab = params.get('tab') || 'equations';

  const concept = CONCEPTS[tab];

  return (
    <div className="space-y-4">
      <PageHeader
        kicker="Mathematics centre"
        title="Quantum Mathematics"
        description="The formal apparatus behind the physics: matrices, complex amplitudes, Hilbert spaces, operators and Dirac notation — with calculators that evaluate real numbers."
        meta={
          <>
            <Chip as="span">KaTeX rendering</Chip>
            <Chip as="span">exact numerics</Chip>
          </>
        }
      />

      <div className="flex flex-wrap gap-1.5 border-b border-[var(--qp-accent)]/10 pb-2">
        {TABS.map((t) => {
          const Icon = t.icon;
          return (
            <button
              key={t.key}
              type="button"
              onClick={() => setParams({ tab: t.key })}
              className={`flex items-center gap-1.5 rounded-t-md px-2.5 py-1.5 text-[11px] transition-colors ${
                tab === t.key
                  ? 'bg-[var(--qp-accent)]/10 text-[#d6f3ff] shadow-[inset_0_-2px_0_0_var(--qp-accent)]'
                  : 'text-[#8fa8c2] hover:text-[#f0f6ff]'
              }`}
            >
              <Icon className="h-3 w-3" /> {t.label}
            </button>
          );
        })}
      </div>

      {tab === 'equations' && <EquationLibrary />}
      {tab === 'linear-algebra' && <MatrixCalculator />}
      {tab === 'complex' && <ComplexVisualiser />}
      {tab === 'vectors' && <VectorVisualiser />}
      {tab === 'probability' && <ProbabilityCalculator />}
      {tab === 'dirac' && <DiracExplorer />}
      {tab === 'graphing' && <GraphPlotter />}
      {tab === 'derivations' && <Derivations />}

      {concept && (
        <div className="grid gap-3 lg:grid-cols-2">
          <Panel className="p-4">
            <h3 className="text-[15px] font-semibold text-[#f0f6ff]">{concept.title}</h3>
            <p className="mt-2 text-[11.5px] leading-relaxed text-[#b6c8dc]">{concept.intro}</p>
            <p className="mt-2 text-[10.5px] leading-relaxed text-[#7088a5]">{concept.note}</p>
          </Panel>
          <div className="space-y-2">
            {concept.points.map((p) => (
              <Panel key={p.tex} soft className="p-3">
                <div className="overflow-x-auto qp-scroll rounded bg-[#071729]/70 px-2.5 py-2">
                  <Formula tex={p.tex} display />
                </div>
                <p className="mt-1.5 text-[10.5px] leading-relaxed text-[#8fa8c2]">{p.text}</p>
              </Panel>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}